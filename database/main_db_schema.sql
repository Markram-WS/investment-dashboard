-- Investment Dashboard Main Database Schema
-- Tables for Manual (Main) and Bot (External) data layers

-- 1. Brokers (owner of contract specs; seeded with 'DF' = Unassigned)
CREATE TABLE IF NOT EXISTS brokers (
    id SERIAL PRIMARY KEY,
    code VARCHAR NOT NULL UNIQUE,          -- 'DF', 'PI', 'CAF'
    name VARCHAR NOT NULL,
    default_margin_rate NUMERIC(10,6) DEFAULT 0,
    currency VARCHAR DEFAULT 'USD',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Portfolio Management
CREATE TABLE IF NOT EXISTS portfolios (
    portfolio_id SERIAL PRIMARY KEY,
    portfolio_name TEXT NOT NULL,
    port_type TEXT NOT NULL,
    -- Risk model (Phase 1): one product per portfolio = broker + ticker.
    broker_id INTEGER REFERENCES brokers(id),
    product_ticker TEXT,
    product_type VARCHAR,            -- identity type; NULL keeps the unique ticker+broker resolution
    x_amount NUMERIC(20,8) NOT NULL DEFAULT 0,   -- adverse move in product price points
    initial_capital NUMERIC(20,8) NOT NULL DEFAULT 0,
    target_ratio JSONB,
    current_nav NUMERIC(20,8) DEFAULT 0.00,
    margin_locked NUMERIC(20,8) DEFAULT 0.00,    -- computed for Active Trading, never user-set
    cash_buffer_limit NUMERIC(20,8) DEFAULT 0.00,
    available_cash NUMERIC(20,8) DEFAULT 0.00,
    trade_plan_md TEXT,
    internal_notes TEXT,           -- Free-text observations (yellow sticky note)
    risk_status TEXT CHECK (risk_status IN ('Safe', 'Warning', 'Danger')),
    tags JSONB,                    -- Metadata tags: {"crypto": true, "bot": true}
    last_rebalance_date DATE,
    data_source TEXT DEFAULT 'Manual' CHECK (data_source IN ('Manual', 'Bot')),
    etl_synced BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. NAV History Tracking
CREATE TABLE IF NOT EXISTS portfolio_nav_history (
    nav_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    nav_date DATE NOT NULL,
    nav_value NUMERIC(20,8) NOT NULL,
    UNIQUE(portfolio_id, nav_date)
);

-- 4. Trade Planning
CREATE TABLE IF NOT EXISTS trade_plans (
    plan_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    entry_zone TEXT,
    exit_zone TEXT,
    tp_levels JSONB,
    sl_level NUMERIC(20,8),
    leverage NUMERIC(20,8),
    margin_rate NUMERIC(20,8),
    entry_reason TEXT,
    data_source TEXT DEFAULT 'Manual' CHECK (data_source IN ('Manual', 'Bot')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. Option Details (with Greeks)
CREATE TABLE IF NOT EXISTS option_details (
    option_id SERIAL PRIMARY KEY,
    strike_price NUMERIC(20,8),
    option_type TEXT CHECK (option_type IN ('Call', 'Put')),
    expiry_date DATE NOT NULL,
    premium_entry NUMERIC(20,8),
    premium_exit NUMERIC(20,8),
    delta_at_entry NUMERIC(10,6),
    IV_at_entry NUMERIC(10,6),
    theta NUMERIC(10,6),
    gamma NUMERIC(10,6),
    vega NUMERIC(10,6),
    rho NUMERIC(10,6),
    underlying_price NUMERIC(20,8)
);

-- Note: `link_type` is NOT stored in the database — it is COMPUTED server-side by `analytics.py._link_type()` based on reciprocal linking detection.
-- Values: "spread" (cross-linked A↔B), "pending_close" (one-way B→A), "primary" (has subs but no outbound link), "none".
-- Unlink: `POST /api/v1/orders/{order_id}/unlink` clears `linked_order_id` on both sides.
-- Column order: `order_id`, `plan_id`, `portfolio_id`, `asset_type`, `side`, `qty`, `entry_price`, `current_price`, `tp_price`, `sl_price`,
--          `leverage`, `margin_rate`, `order_status`, `group_id`, `linked_order_id`, `executed_by`, `option_id`, `data_source`,
--          `contract_type`, `direction`, `expiry_date`, `strike_price`, `cost`, `remark`, `etl_synced`, `created_at`

-- 6. Active Orders (order_id is TEXT UUID, auto-generated by backend or client-provided)
CREATE TABLE IF NOT EXISTS active_orders (
    order_id TEXT PRIMARY KEY,
    plan_id INTEGER NOT NULL REFERENCES trade_plans(plan_id) ON DELETE CASCADE,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    asset_type TEXT NOT NULL,
    side TEXT NOT NULL,
    qty NUMERIC(20,8),
    entry_price NUMERIC(20,8),
    current_price NUMERIC(20,8),
    tp_price NUMERIC(20,8),
    sl_price NUMERIC(20,8),
    leverage NUMERIC(20,8),
    margin_rate NUMERIC(20,8),
    order_status TEXT DEFAULT 'pending_sync',
    group_id INTEGER REFERENCES orders_groups(id) ON DELETE SET NULL,
    linked_order_id TEXT,
    executed_by TEXT,
    option_id INTEGER REFERENCES option_details(option_id),
    data_source TEXT DEFAULT 'Manual' CHECK (data_source IN ('Manual', 'Bot')),
    contract_type TEXT DEFAULT 'spot' CHECK (contract_type IN ('spot', 'future', 'option')),
    direction TEXT,
    expiry_date TIMESTAMP,
    strike_price NUMERIC(20,8),
    cost NUMERIC(20,8) DEFAULT 0,
    remark VARCHAR,
    etl_synced BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 7. Simulation Models
CREATE TABLE IF NOT EXISTS simulation_models (
    sim_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    model_name TEXT NOT NULL,
    draft_data JSONB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(portfolio_id, model_name)
);

-- 8. Trade History & Audit (order_id references active_orders; close_order_id is UUID from close action; group_id stores group at close/cancel time)
CREATE TABLE IF NOT EXISTS trade_history (
    history_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    order_id TEXT,  -- reference only, FK removed
    close_order_id TEXT,
    group_id INTEGER,  -- group reference at time of close/cancel
    type TEXT NOT NULL,
    asset TEXT NOT NULL,
    amount NUMERIC(20,8),
    entry_price NUMERIC(20,8),
    exit_price NUMERIC(20,8),
    realized_pl NUMERIC(20,8),
    executed_by TEXT,
    decision_note TEXT,
    entry_date TIMESTAMP,
    exit_date TIMESTAMP,
    remark JSONB,
    order_remark VARCHAR,
    data_source TEXT DEFAULT 'Manual' CHECK (data_source IN ('Manual', 'Bot')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. Zone Group Definitions (per-portfolio zone config with price ranges)
CREATE TABLE IF NOT EXISTS orders_groups (
    id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    max_orders INTEGER,
    min_price NUMERIC(20,8),
    max_price NUMERIC(20,8),
    range NUMERIC(20,8),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 10. Asset Registry (broker-scoped products, contract symbols, provider quotes)
-- This is the live main-database registry. The legacy, mockup-only
-- `whitelist_assets` table is no longer canonical: the FastAPI startup
-- migration creates the three tables below, converts every legacy row to one
-- product + one symbol + quote(s), asserts the conversion invariants inside the
-- same transaction, and only then DROPs `whitelist_assets`. The whole legacy
-- branch runs only when the legacy table still exists, so later boots are a
-- no-op. `Base.metadata.create_all` deliberately excludes both the legacy table
-- and these registry tables; the migration owns their DDL.
--
-- PostgreSQL 15 is canonical: the product natural key uses
-- `UNIQUE NULLS NOT DISTINCT`, and the symbol table installs the three
-- partial/expression indexes below. SQLite uses the portable unique constraint
-- only and cannot enforce those indexes.

-- `asset_groups` (referenced by group_id) and `custom_portfolio_connections`
-- are created by the application's SQLAlchemy metadata; they are described in
-- database/README.md.
--
-- Broker-scoped product. Identity is (ticker, broker_id, asset_type), with
-- NULLs treated as equal on PostgreSQL so the internal default product
-- (ticker/broker/type all NULL) cannot be duplicated. The default product is
-- never listed and is not editable.
CREATE TABLE IF NOT EXISTS asset_products (
    product_id SERIAL PRIMARY KEY,
    ticker VARCHAR,
    broker_id INTEGER REFERENCES brokers(id),
    asset_type VARCHAR,
    multiplier NUMERIC(20,8) NOT NULL DEFAULT 1,
    margin_rate NUMERIC(10,6) NOT NULL DEFAULT 0,
    source VARCHAR DEFAULT '-',                 -- 'yfinance', 'tfex', 'manual', or '-' (no feed)
    margin_mode VARCHAR NOT NULL DEFAULT 'notional',
    margin_per_contract NUMERIC(20,8),
    group_id INTEGER REFERENCES asset_groups(id),
    name VARCHAR,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_asset_product_identity
        UNIQUE NULLS NOT DISTINCT (ticker, broker_id, asset_type),
    CONSTRAINT ck_asset_product_margin_mode
        CHECK (margin_mode IN ('notional', 'premium', 'span'))
);

-- Contract symbol belonging to a product. `price_symbol` is the dashboard /
-- order key (the symbol an order's asset_type must match); `sync_symbol` is the
-- case-preserving provider key used to fetch and store a quote. They may differ
-- (for example dashboard `PTT` vs provider `PTT.BK`). The broker mirror is kept
-- equal to the owning product's broker by the application and is never exposed
-- by the API.
CREATE TABLE IF NOT EXISTS asset_symbols (
    symbol_id SERIAL PRIMARY KEY,
    product_id INTEGER NOT NULL
        REFERENCES asset_products(product_id) ON DELETE CASCADE,
    broker_id INTEGER REFERENCES brokers(id),
    price_symbol VARCHAR,
    sync_symbol VARCHAR NOT NULL,
    contract_kind VARCHAR DEFAULT 'future',
    option_type VARCHAR,
    expiry_date DATE,
    strike_price NUMERIC(20,8),
    multiplier_override NUMERIC(20,8),
    margin_rate_override NUMERIC(10,6),
    margin_per_contract NUMERIC(20,8),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- Dashboard keys are unique per product and per broker, compared normalized
-- (upper(trim(...))) and only when a dashboard key exists.
CREATE UNIQUE INDEX IF NOT EXISTS uq_asset_symbol_product_dashboard
    ON asset_symbols (product_id, upper(trim(price_symbol)))
    WHERE price_symbol IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_asset_symbol_broker_dashboard
    ON asset_symbols (broker_id, upper(trim(price_symbol)))
    WHERE price_symbol IS NOT NULL;
-- Option contracts without a dashboard key are identified by their terms.
CREATE UNIQUE INDEX IF NOT EXISTS uq_asset_symbol_option_identity
    ON asset_symbols (product_id, expiry_date, strike_price, option_type)
    WHERE contract_kind = 'option' AND price_symbol IS NULL;

-- Latest provider quote, keyed by the case-preserving provider symbol. Quote
-- rows have no foreign key: deleting a symbol/product removes a quote only when
-- no remaining symbol references the same (source, sync_symbol).
CREATE TABLE IF NOT EXISTS asset_quotes (
    source VARCHAR NOT NULL,
    sync_symbol VARCHAR NOT NULL,
    price NUMERIC(20,8),
    change_24h NUMERIC(10,4),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (source, sync_symbol)
);

CREATE TABLE IF NOT EXISTS watchlist (
    watch_id SERIAL PRIMARY KEY,
    ticker TEXT NOT NULL,
    alert_price NUMERIC(20,8),
    notes TEXT
);

-- 11. Transaction Model (Consolidated Ledger)
CREATE TABLE IF NOT EXISTS transactions (
    transaction_id SERIAL PRIMARY KEY,
    transaction_type TEXT NOT NULL,
    asset TEXT NOT NULL,
    amount NUMERIC(20,8) NOT NULL,
    source_portfolio_id INTEGER REFERENCES portfolios(portfolio_id),
    destination_portfolio_id INTEGER REFERENCES portfolios(portfolio_id),
    executed_by TEXT NOT NULL,
    status TEXT DEFAULT 'completed',
    reference_id TEXT,
    audit_labels JSONB,
    data_source TEXT DEFAULT 'Manual' CHECK (data_source IN ('Manual', 'Bot')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 12. Decision Journal (Section 2.3 - Mini Post-it Notes)
CREATE TABLE IF NOT EXISTS decision_journals (
    journal_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    history_id INTEGER REFERENCES trade_history(history_id) ON DELETE SET NULL,
    entry_text TEXT NOT NULL,
    data_source TEXT DEFAULT 'Manual' CHECK (data_source IN ('Manual', 'Bot')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 13. Managed Fund Tables (separate from Active Trading)
CREATE TABLE IF NOT EXISTS managed_fund_holdings (
    holding_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    asset TEXT NOT NULL,
    qty NUMERIC(20,8) NOT NULL DEFAULT 0,
    avg_entry_price NUMERIC(20,8) DEFAULT 0,
    current_price NUMERIC(20,8) DEFAULT 0,
    market_value NUMERIC(20,8) DEFAULT 0,
    unrealized_pl NUMERIC(20,8) DEFAULT 0,
    unrealized_pl_pct NUMERIC(10,4) DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS managed_fund_orders (
    order_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    asset TEXT NOT NULL,
    side TEXT NOT NULL,
    qty NUMERIC(20,8) NOT NULL,
    price NUMERIC(20,8),
    status TEXT NOT NULL DEFAULT 'pending',
    order_type TEXT NOT NULL DEFAULT 'manual',
    notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS managed_fund_order_history (
    history_id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE,
    asset TEXT NOT NULL,
    side TEXT NOT NULL,
    qty NUMERIC(20,8) NOT NULL,
    price NUMERIC(20,8),
    status TEXT NOT NULL,
    order_type TEXT NOT NULL DEFAULT 'manual',
    notes TEXT,
    executed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS managed_fund_settings (
    id SERIAL PRIMARY KEY,
    portfolio_id INTEGER NOT NULL REFERENCES portfolios(portfolio_id) ON DELETE CASCADE UNIQUE,
    target_ratio JSONB,
    total_invested NUMERIC(20,8) DEFAULT 0,
    last_rebalance_date TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
