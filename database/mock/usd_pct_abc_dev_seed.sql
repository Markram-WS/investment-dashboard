-- Idempotent: creates the schema/tables if absent, then replaces the mock rows.

CREATE SCHEMA IF NOT EXISTS usd_pct_abc;

CREATE TABLE IF NOT EXISTS usd_pct_abc.opened_orders (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tm timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    symbol varchar(20),
    orderno varchar(50) UNIQUE,
    position varchar(10) NOT NULL,
    side varchar(10) NOT NULL,
    volume double precision NOT NULL,
    price double precision NOT NULL,
    status varchar(10) NOT NULL,
    c_tm timestamp,
    c_orderno varchar(50),
    c_position varchar(10),
    c_side varchar(10),
    c_volume double precision,
    c_price double precision,
    c_status varchar(10),
    tp double precision,
    mark_price double precision,
    fee double precision,
    pl double precision,
    remark varchar(512)
);

CREATE TABLE IF NOT EXISTS usd_pct_abc.order_history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tm timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    symbol varchar(20),
    orderno varchar(50),
    position varchar(10) NOT NULL,
    side varchar(10) NOT NULL,
    volume double precision NOT NULL,
    price double precision NOT NULL,
    status varchar(10) NOT NULL,
    c_tm timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    c_symbol varchar(20),
    c_orderno varchar(50),
    c_position varchar(10),
    c_side varchar(10),
    c_volume double precision,
    c_price double precision,
    c_status varchar(10),
    tp double precision,
    mark_price double precision,
    fee double precision,
    pl double precision,
    remark varchar(512)
);

